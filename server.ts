import express, { Request, Response } from 'express';
import { GoogleGenAI } from '@google/genai';
import dotenv from 'dotenv';
import path from 'path';
import { fileURLToPath } from 'url';

dotenv.config();

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const app = express();
const PORT = process.env.PORT || 3000;

app.use(express.json());

// API route for TTS voice generation using Gemini 3.8 Flash Lite TTS
app.post('/api/tts', async (req: Request, res: Response) => {
  try {
    const { text } = req.body;
    if (!text || typeof text !== 'string') {
      res.status(400).json({ error: 'Text is required for TTS generation' });
      return;
    }

    const apiKey = process.env.GEMINI_API_KEY;
    if (!apiKey) {
      // Return 503 so client cleanly falls back to Web Speech API
      res.status(503).json({ error: 'Gemini API key not configured on server', fallback: true });
      return;
    }

    const ai = new GoogleGenAI({ apiKey });

    // Use gemini-3.8-flash-lite-tts for high efficiency audio generation
    const interaction = await ai.interactions.create({
      model: 'gemini-3.8-flash-lite-tts',
      input: [
        {
          type: 'text',
          text: text,
          annotations: [
            {
              type: 'speech_metadata',
              style: 'Warm, clear, confident and natural professional tone',
            },
          ],
        },
      ],
      response_format: { type: 'audio' },
      generation_config: {
        speech_config: [
          {
            language: 'en-US',
            voice: 'Kore', // 'Kore', 'Puck', 'Charon', 'Fenrir', 'Zephyr'
          },
        ],
      },
    });

    const audio = interaction.output_audio;
    if (audio?.data) {
      res.json({
        audioBase64: audio.data,
        mimeType: audio.mime_type || 'audio/wav',
      });
      return;
    }

    res.status(500).json({ error: 'No audio generated by model', fallback: true });
  } catch (error: any) {
    console.error('TTS Generation error:', error);
    res.status(500).json({
      error: error.message || 'Failed to generate speech',
      fallback: true,
    });
  }
});

// Mount Vite middleware in development or serve static in production
async function startServer() {
  const isProduction = process.env.NODE_ENV === 'production';

  if (!isProduction) {
    const { createServer: createViteServer } = await import('vite');
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: 'spa',
    });
    app.use(vite.middlewares);
  } else {
    app.use(express.static(path.resolve(__dirname, 'dist')));
    app.get('*', (_req, res) => {
      res.sendFile(path.resolve(__dirname, 'dist', 'index.html'));
    });
  }

  app.listen(Number(PORT), '0.0.0.0', () => {
    console.log(`Server listening on http://0.0.0.0:${PORT}`);
  });
}

startServer();
